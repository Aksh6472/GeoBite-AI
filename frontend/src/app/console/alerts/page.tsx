"use client";

import { Download, Plus, RefreshCcw } from "lucide-react";
import Link from "next/link";
import { useState } from "react";
import { Badge, Button, Card, Empty, ErrorBanner, Field, Input, PageHeader, Select, Skeleton, STATUS_TONE, Table, Tabs } from "@/components/ui";
import { api, downloadUrl } from "@/lib/api";
import { ADMIN_ROLES, useAuth } from "@/lib/auth";
import { fmtDate } from "@/lib/format";
import { useApi, useGeoTree, useVocab } from "@/lib/hooks";

type Alert = { id: number; alert_code: string; title: string; ward: string; district: string; alert_type_label: string; severity: string; status: string; status_label: string; assigned_to: { name: string; role: string } | null; generated_by: string; created_at: string; due_date: string | null };

export default function AlertsPage() {
  const { user } = useAuth();
  const vocab = useVocab();
  const { districts } = useGeoTree();
  const isAdmin = !!user && ADMIN_ROLES.includes(user.role);
  const [view, setView] = useState<"open" | "mine" | "closed">(isAdmin ? "open" : "mine");
  const [type, setType] = useState("");
  const [district, setDistrict] = useState("");
  const [creating, setCreating] = useState(false);
  const [msg, setMsg] = useState<string | null>(null);
  const params = { alert_type: type, district_id: district, mine: view === "mine" ? true : undefined, status: view === "closed" ? "closed" : undefined, limit: 200 };
  const { data, error, loading, reload } = useApi<{ total: number; items: Alert[] }>("/alerts", params);

  const evaluate = async () => {
    const r = await api<{ created: string[] }>("/alerts/evaluate", { method: "POST" });
    setMsg(r.created.length ? `${r.created.length} new alert(s) generated: ${r.created.join(", ")}` : "Rules evaluated. No new alerts; open alerts were refreshed with current evidence.");
    reload();
  };

  return (
    <>
      <PageHeader
        title="Alerts and interventions"
        subtitle="Alerts are generated by explicit, auditable rules (or raised manually), then reviewed, verified in the field, acted on with humane interventions and closed."
        actions={<>
          <a href={downloadUrl("/analytics/export/alerts.csv")} className="inline-flex h-10 items-center gap-2 rounded-lg border border-line bg-white px-4 text-sm font-medium text-navy-800 hover:bg-navy-50"><Download className="size-4" />Export</a>
          {isAdmin && <Button variant="secondary" onClick={evaluate}><RefreshCcw className="size-4" />Run alert rules</Button>}
          <Button onClick={() => setCreating(!creating)}><Plus className="size-4" />Raise alert</Button>
        </>}
      />
      {msg && <p className="mb-4 rounded-lg bg-teal-50 px-3 py-2 text-[13px] text-teal-700">{msg}</p>}
      {creating && <NewAlert onDone={() => { setCreating(false); reload(); }} />}
      <div className="mb-4 flex flex-wrap items-center gap-2">
        <Tabs value={view} onChange={setView} items={[{ value: "open", label: "Open" }, { value: "mine", label: "Assigned to me" }, { value: "closed", label: "Closed" }]} />
        <Select aria-label="Alert type" className="w-full sm:w-64" placeholder="All alert types" value={type} options={vocab?.alert_types ?? []} onChange={(e) => setType(e.target.value)} />
        <Select aria-label="District" className="w-full sm:w-48" placeholder="All districts" value={district} options={districts.map((d) => ({ value: d.id, label: d.name }))} onChange={(e) => setDistrict(e.target.value)} />
      </div>
      <Card>
        <ErrorBanner error={error} onRetry={reload} />
        {loading && !data ? <div className="space-y-2 p-4">{[0, 1, 2, 3, 4].map((i) => <Skeleton key={i} className="h-10" />)}</div> : data?.items.length === 0 ? <Empty title="No alerts in this view">{view === "mine" ? "Alerts assigned to you will appear here." : "Nothing matches these filters."}</Empty> : (
          <Table head={["Alert", "Ward", "Type", "Severity", "Status", "Assigned to", "Raised"]}>
            {data?.items.map((a) => (
              <tr key={a.id} className="hover:bg-canvas/70">
                <td className="px-4 py-3"><Link href={`/console/alerts/${a.id}`} className="font-medium text-navy-900 hover:underline">{a.title}</Link><span className="block font-mono text-[11.5px] text-muted">{a.alert_code} · {a.generated_by}</span></td>
                <td className="px-4 py-3">{a.ward}<span className="block text-xs text-muted">{a.district}</span></td>
                <td className="px-4 py-3 text-muted">{a.alert_type_label}</td>
                <td className="px-4 py-3"><Badge tone={STATUS_TONE[a.severity]}>{a.severity}</Badge></td>
                <td className="px-4 py-3"><Badge tone={STATUS_TONE[a.status]}>{a.status_label}</Badge></td>
                <td className="px-4 py-3">{a.assigned_to ? <>{a.assigned_to.name}<span className="block text-xs text-muted">{a.assigned_to.role}</span></> : <span className="text-muted">Unassigned</span>}</td>
                <td className="whitespace-nowrap px-4 py-3 text-muted">{fmtDate(a.created_at)}</td>
              </tr>
            ))}
          </Table>
        )}
      </Card>
    </>
  );
}

function NewAlert({ onDone }: { onDone: () => void }) {
  const vocab = useVocab();
  const { districts } = useGeoTree();
  const wards = districts.flatMap((d) => (d.children ?? []).flatMap((m) => (m.children ?? []).map((w) => ({ value: w.id, label: `${w.name} · ${d.name}` }))));
  const [f, setF] = useState({ ward_id: "", alert_type: "repeated_behaviour", severity: "medium", title: "", notes: "" });
  const [err, setErr] = useState<Error | null>(null);
  return (
    <Card className="mb-5 p-5">
      <form className="grid gap-4 md:grid-cols-4" onSubmit={async (e) => { e.preventDefault(); try { await api("/alerts", { method: "POST", json: { ...f, ward_id: Number(f.ward_id) } }); onDone(); } catch (x) { setErr(x as Error); } }}>
        <div className="md:col-span-4"><ErrorBanner error={err} /></div>
        <Field label="Ward" htmlFor="w" required><Select id="w" placeholder="Select ward" value={f.ward_id} options={wards} onChange={(e) => setF({ ...f, ward_id: e.target.value })} /></Field>
        <Field label="Type" htmlFor="t"><Select id="t" value={f.alert_type} options={vocab?.alert_types ?? []} onChange={(e) => setF({ ...f, alert_type: e.target.value })} /></Field>
        <Field label="Severity" htmlFor="s"><Select id="s" value={f.severity} options={[{ value: "low", label: "Low" }, { value: "medium", label: "Medium" }, { value: "high", label: "High" }]} onChange={(e) => setF({ ...f, severity: e.target.value })} /></Field>
        <Field label="Title" htmlFor="ti" required><Input id="ti" value={f.title} onChange={(e) => setF({ ...f, title: e.target.value })} /></Field>
        <Field label="Notes / evidence" htmlFor="n" className="md:col-span-3"><Input id="n" value={f.notes} onChange={(e) => setF({ ...f, notes: e.target.value })} /></Field>
        <div className="flex items-end"><Button type="submit" className="w-full">Raise alert</Button></div>
      </form>
    </Card>
  );
}
